# operadores de asignacion = += -= *= /= //= **=

edad = 55 # asignación de valor a una variable 
print(edad)
edad += 5 # suma y reasigna el valor de la variable edad es una 
#suma al valor original y luego se asigna como edad el nuevo valor 
print(edad)
# ejemplo explicito
edad = edad + 5
print(edad)

# ejemplo con resta
edad -= 10 # resta y reasign
print(edad)

print("operadores de asignacion que se pueden utilizar son: = += -= *= /= //= **=")

